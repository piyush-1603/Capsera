-- 17. Certificates Table (Course completion certificates)
CREATE TABLE IF NOT EXISTS certificates (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trainee_id INT NOT NULL,
  course_id INT NOT NULL,
  certificate_code VARCHAR(64) NOT NULL,
  issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  revoked_at TIMESTAMPTZ,
  CONSTRAINT uq_certificates_code UNIQUE (certificate_code),
  CONSTRAINT uq_certificates_trainee_course UNIQUE (trainee_id, course_id),
  CONSTRAINT fk_certificates_trainee FOREIGN KEY (trainee_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_certificates_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_certificates_trainee_id ON certificates (trainee_id);
CREATE INDEX IF NOT EXISTS idx_certificates_course_id ON certificates (course_id);
CREATE INDEX IF NOT EXISTS idx_certificates_issued_at ON certificates (issued_at);

-- 18. Announcements Table (Platform announcements published by administrators)
CREATE TABLE IF NOT EXISTS announcements (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id INT NOT NULL,
  title VARCHAR(255) NOT NULL,
  body TEXT NOT NULL,
  category VARCHAR(50),
  status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
  published_at TIMESTAMPTZ,
  expires_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_announcements_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
  CONSTRAINT fk_announcements_admin FOREIGN KEY (admin_id) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_announcements_admin_id ON announcements (admin_id);
CREATE INDEX IF NOT EXISTS idx_announcements_status_published ON announcements (status, published_at);
CREATE INDEX IF NOT EXISTS idx_announcements_expires_at ON announcements (expires_at);

DROP TRIGGER IF EXISTS trg_announcements_updated_at ON announcements;
CREATE TRIGGER trg_announcements_updated_at
BEFORE UPDATE ON announcements
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 19. Audit Logs Table (Administrative actions and compliance event trail)
-- Security rule: Passwords, tokens, or other secrets must NEVER be persisted in metadata.
CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id INT,
  action VARCHAR(100) NOT NULL,
  entity_type VARCHAR(50) NOT NULL,
  entity_id VARCHAR(100) NOT NULL,
  metadata JSONB,
  ip_address VARCHAR(45),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_audit_logs_actor FOREIGN KEY (actor_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_audit_logs_actor ON audit_logs (actor_id, created_at);
CREATE INDEX IF NOT EXISTS idx_audit_logs_entity ON audit_logs (entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_audit_logs_action ON audit_logs (action, created_at);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at ON audit_logs (created_at);
CREATE INDEX IF NOT EXISTS idx_audit_logs_metadata ON audit_logs USING gin (metadata);
