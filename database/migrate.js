import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Resolve dependencies from server/package.json
const serverRequire = createRequire(path.resolve(__dirname, '../server/package.json'));
const dotenv = serverRequire('dotenv');
const { Pool } = serverRequire('pg');

// Load environment variables from server/.env if available
const envPath = path.resolve(__dirname, '../server/.env');
if (fs.existsSync(envPath)) {
  dotenv.config({ path: envPath });
} else {
  dotenv.config();
}

const pool = new Pool({
  host: process.env.DB_HOST || 'localhost',
  port: parseInt(process.env.DB_PORT || '5432', 10),
  user: process.env.DB_USER || 'postgres',
  password: process.env.DB_PASSWORD || undefined,
  database: process.env.DB_NAME || 'capsera_db',
  ssl: process.env.DB_SSL === 'true' ? { rejectUnauthorized: false } : false,
});

async function runMigrations() {
  const isStatusOnly = process.argv.includes('--status');
  const client = await pool.connect();

  try {
    // 1. Ensure tracking table exists
    await client.query(`
      CREATE TABLE IF NOT EXISTS schema_migrations (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        version VARCHAR(255) NOT NULL UNIQUE,
        applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );
    `);

    // 2. Fetch already-applied migrations
    const res = await client.query('SELECT version, applied_at FROM schema_migrations ORDER BY id ASC;');
    const appliedMap = new Map(res.rows.map(r => [r.version, r.applied_at]));

    // 3. Read migration files
    const migrationsDir = path.resolve(__dirname, 'migrations');
    const files = fs.readdirSync(migrationsDir)
      .filter(f => f.endsWith('.sql'))
      .sort();

    console.log(`\n========================================`);
    console.log(`  CAPSERA PostgreSQL Migration Runner  `);
    console.log(`  Database: ${process.env.DB_NAME || 'capsera_db'} on ${process.env.DB_HOST || 'localhost'}:${process.env.DB_PORT || '5432'}`);
    console.log(`========================================\n`);

    if (isStatusOnly) {
      console.log('Migration Status:');
      for (const file of files) {
        if (appliedMap.has(file)) {
          console.log(`  [APPLIED]  ${file} (applied: ${appliedMap.get(file).toISOString()})`);
        } else {
          console.log(`  [PENDING]  ${file}`);
        }
      }
      return;
    }

    let appliedCount = 0;
    for (const file of files) {
      if (appliedMap.has(file)) {
        console.log(`  [SKIP]  ${file} (already applied at ${appliedMap.get(file).toISOString()})`);
        continue;
      }

      console.log(`  [EXEC]  Applying ${file}...`);
      const filePath = path.join(migrationsDir, file);
      const sql = fs.readFileSync(filePath, 'utf8');

      // Execute inside an isolated transaction
      await client.query('BEGIN');
      try {
        await client.query(sql);
        await client.query('INSERT INTO schema_migrations (version) VALUES ($1);', [file]);
        await client.query('COMMIT');
        console.log(`  [DONE]  Successfully applied ${file}`);
        appliedCount++;
      } catch (err) {
        await client.query('ROLLBACK');
        console.error(`\n[ERROR] Migration failed in ${file}! Transaction rolled back.`);
        console.error(err.message);
        throw err;
      }
    }

    console.log(`\nMigration run completed. Newly applied: ${appliedCount}, Total tracked: ${files.length}\n`);
  } finally {
    client.release();
    await pool.end();
  }
}

runMigrations().catch(err => {
  console.error('\nMigration runner failed:', err);
  process.exit(1);
});
