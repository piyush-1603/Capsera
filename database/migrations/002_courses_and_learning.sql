-- 7. Courses Table
CREATE TABLE IF NOT EXISTS courses (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trainer_id INT NOT NULL,
  title VARCHAR(255) NOT NULL,
  summary VARCHAR(500),
  description TEXT,
  subject VARCHAR(100),
  level VARCHAR(20),
  status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
  thumbnail_url VARCHAR(1000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_courses_level CHECK (level IS NULL OR level IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED')),
  CONSTRAINT chk_courses_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
  CONSTRAINT fk_courses_trainer FOREIGN KEY (trainer_id) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_courses_trainer_id ON courses (trainer_id);
CREATE INDEX IF NOT EXISTS idx_courses_status ON courses (status);
CREATE INDEX IF NOT EXISTS idx_courses_subject ON courses (subject);

DROP TRIGGER IF EXISTS trg_courses_updated_at ON courses;
CREATE TRIGGER trg_courses_updated_at
BEFORE UPDATE ON courses
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 8. Lessons Table (Ordered content units within a course)
CREATE TABLE IF NOT EXISTS lessons (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id INT NOT NULL,
  title VARCHAR(255) NOT NULL,
  content TEXT,
  sort_order INT NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_lessons_id_course UNIQUE (id, course_id),
  CONSTRAINT fk_lessons_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_lessons_course_id ON lessons (course_id);
CREATE INDEX IF NOT EXISTS idx_lessons_course_order ON lessons (course_id, sort_order);

DROP TRIGGER IF EXISTS trg_lessons_updated_at ON lessons;
CREATE TRIGGER trg_lessons_updated_at
BEFORE UPDATE ON lessons
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 9. Learning Resources Table (Files, links, media attached to course or lesson)
CREATE TABLE IF NOT EXISTS learning_resources (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id INT NOT NULL,
  lesson_id INT,
  title VARCHAR(255) NOT NULL,
  type VARCHAR(20) NOT NULL,
  url VARCHAR(2000) NOT NULL,
  file_size BIGINT,
  mime_type VARCHAR(100),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_resources_type CHECK (type IN ('VIDEO', 'PRESENTATION', 'DOCUMENT', 'LINK', 'OTHER')),
  CONSTRAINT fk_learning_resources_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE CASCADE,
  CONSTRAINT fk_learning_resources_lesson FOREIGN KEY (lesson_id) REFERENCES lessons (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_learning_resources_course_id ON learning_resources (course_id);
CREATE INDEX IF NOT EXISTS idx_learning_resources_lesson_id ON learning_resources (lesson_id);

-- 10. Enrollments Table (Trainee course enrollment lifecycle)
CREATE TABLE IF NOT EXISTS enrollments (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trainee_id INT NOT NULL,
  course_id INT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  enrolled_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at TIMESTAMPTZ,
  CONSTRAINT uq_enrollments_trainee_course UNIQUE (trainee_id, course_id),
  CONSTRAINT uq_enrollments_id_course UNIQUE (id, course_id),
  CONSTRAINT chk_enrollments_status CHECK (status IN ('ACTIVE', 'COMPLETED', 'CANCELLED')),
  CONSTRAINT fk_enrollments_trainee FOREIGN KEY (trainee_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_enrollments_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_enrollments_trainee_id ON enrollments (trainee_id);
CREATE INDEX IF NOT EXISTS idx_enrollments_course_id ON enrollments (course_id);
CREATE INDEX IF NOT EXISTS idx_enrollments_status ON enrollments (status);

-- 11. Lesson Progress Table
-- Composite foreign keys guarantee at the DB engine level that the completed lesson belongs to the enrolled course.
CREATE TABLE IF NOT EXISTS lesson_progress (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enrollment_id INT NOT NULL,
  course_id INT NOT NULL,
  lesson_id INT NOT NULL,
  completed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_lesson_progress_enrollment_lesson UNIQUE (enrollment_id, lesson_id),
  CONSTRAINT fk_lesson_progress_enrollment_course FOREIGN KEY (enrollment_id, course_id) REFERENCES enrollments (id, course_id) ON DELETE CASCADE,
  CONSTRAINT fk_lesson_progress_lesson_course FOREIGN KEY (lesson_id, course_id) REFERENCES lessons (id, course_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_lesson_progress_enrollment_id ON lesson_progress (enrollment_id);
CREATE INDEX IF NOT EXISTS idx_lesson_progress_lesson_id ON lesson_progress (lesson_id);
CREATE INDEX IF NOT EXISTS idx_lesson_progress_course_id ON lesson_progress (course_id);
